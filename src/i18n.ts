export const messages: Record<Language, Record<MessageKey, string>> = { en, hi, pa };
export const LANGUAGE_LABEL: Record<Language, string> = { en: 'English', hi: 'हिन्दी', pa: 'ਪੰਜਾਬੀ' };
const LOCALE: Record<Language, string> = { en: 'en-IN', hi: 'hi-IN', pa: 'pa-IN' };

export type T = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(lang: Language): T {
  return (key, vars) => messages[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? ''));
}

export function formatMoney(paise: number, lang: Language): string {
  return new Intl.NumberFormat(LOCALE[lang], { style: 'currency', currency: 'INR', minimumFractionDigits: paise % 100 ? 2 : 0, maximumFractionDigits: 2 }).format(paise / 100);
}

export function formatDate(isoDate: string, lang: Language): string {
  return new Intl.DateTimeFormat(LOCALE[lang], { day: 'numeric', month: 'short', year: 'numeric' }).format(new Date(`${isoDate.slice(0, 10)}T12:00:00`));
}
